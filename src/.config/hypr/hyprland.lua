-- Load External Variables
--
-- An error in this file aborts the whole config, leaving no binds at all (not
-- even a terminal or exit), whereas hyprlang's `source =` just skipped a
-- missing file. So anything that can be missing is loaded through pcall and
-- reported with an on-screen notification instead.
-- At login the config is parsed before any output exists, so a notification
-- made then may never be seen; warnings are kept and shown again once
-- Hyprland has started (reloads don't fire hyprland.start, but there the
-- immediate notification works).
local warnings = {}
local function show_warning(message)
    pcall(hl.notification.create, { text = "hyprland.lua: " .. message, timeout = 15000 })
end
local function warn(message)
    table.insert(warnings, message)
    show_warning(message)
end
hl.on("hyprland.start", function()
    for _, message in ipairs(warnings) do
        show_warning(message)
    end
end)

